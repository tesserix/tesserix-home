import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { expect, it } from "vitest";
import provenance from "./staff-recovery.provenance.json";
it("retains the exact owner-generated receipt models with immutable provenance", () => {
  const artifact = readFileSync(
    new URL("./staff-recovery.ts", import.meta.url),
  );
  expect(provenance.repository).toBe("tesserix/onboarding-service");
  expect(provenance.revision).toMatch(/^[a-f0-9]{40}$/);
  expect(provenance.path).toBe("contracts/staff-recovery.ts");
  expect(createHash("sha256").update(artifact).digest("hex")).toBe(
    provenance.sha256,
  );
  expect(artifact.toString()).toContain(
    "Code generated by onboarding-service/apps/api/cmd/staff-contracts. DO NOT EDIT.",
  );
});
